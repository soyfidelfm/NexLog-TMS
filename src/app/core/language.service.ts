@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly lang = signal<Lang>('en');
  readonly t = computed(() => translations[this.lang()]);

  setLang(lang: Lang): void {
    this.lang.set(lang);
  }

  toggle(): void {
    this.lang.update(l => (l === 'en' ? 'es' : 'en'));
  }
}
